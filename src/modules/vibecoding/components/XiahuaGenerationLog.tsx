export default function XiahuaGenerationLog() {
  let i = 0
  return (
    <div>
      {TURNS.map((t, idx) => {
        const key = `${t.k}-${idx}`
        if (t.k === 'think') return <ToolStatus key={key} title={t.title} lines={t.lines} running={false} />
        const at = i++
        if (t.k === 'doc') return <DocAttachment key={key} index={at} text={t.text} />
        if (t.k === 'me') return <UserMessage key={key} text={t.text} index={at} />
        return <AssistantMessage key={key} text={t.text} cards={t.cards} index={at} />
      })}
    </div>
  )
}
